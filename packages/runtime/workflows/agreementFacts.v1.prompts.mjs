// are both frozen; widening either to carry agreement fields would mean every agreement wording
// change is a change to THAT lane's frozen prompt, and a rollback of one would be a rollback of
// the other. So this family gets its own prompts, its own behaviour, its own dispatch reads, its
// own engine identity and its own entry — and pays the cost of some duplicated shape to buy
// independently versionable questionnaires.
//
// WHAT IS SHARED IS SHARED DELIBERATELY AND IS PINNED AS SUCH. Two sentences below are carried
// VERBATIM from the invoice family's live prompt — the inert-data posture (PRD §6 law 5) and the
// never-infer-never-compute rule — because they are the estate's ratified wording for rules that
// are not agreement-specific, and restating them in this file's own words would let the two
// drift. `agreement-facts-v1.test.mjs` reads BOTH modules and asserts the carriage is byte-exact,
// so "verbatim" is a checked fact rather than a claim in a comment.
//
// THE TWO RULES THIS FAMILY ADDS.
//   SHE NEVER SUMS. An agreement prints a cash price, a deposit, an amount financed, charges, a
//   total payable and often a whole repayment schedule. The single most tempting wrong answer a
//   model can give is a figure it worked out: 120,000 minus a 20,000 deposit is 100,000, and a
//   model that "helpfully" fills an unprinted amount financed has invented a liability. Every
//   arithmetic result in an agreement fact state is produced by
//   `clara.evaluate_agreement_contract_state_v1` from quoted renderings.
//   SHE NEVER CLASSIFIES. Whether this page is a hire purchase, a finance lease, a tenancy or
//   something else is decided by that same evaluator, from the rendering the page uses for
//   ITSELF, against a closed keyword roster. The model's job on `contract.agreement.kind` is to
//   quote the heading, not to judge it — a model that answered "hire purchase" for a page headed
//   "Perjanjian Sewa" would have posted an asset and a liability that do not exist.
//
// Do NOT edit this file or its import closure once deployed (ARCHITECTURE Appendix A
// immutability). A behavioural change — INCLUDING A PROMPT TWEAK, which is why the prompts sit
// inside the closure — ships as agreementFacts.v2.

