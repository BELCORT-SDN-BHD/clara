/** The text channel's user prompt: the numbered regions, bounded. The `idx` is the DATABASE's own
 *  numbering (clara.witness_citation_regions — the estate's one region numbering, which
 *  clara.persist_agreement_facts resolves a citation against through the same ordering), so a
 *  region dropped for length keeps every other region's number exactly where it was. */
export function buildAgreementTextPrompt({ regions }) {
  const lines = [];
  let used = 0;
  let shown = 0;
  let truncated = false;
  for (const r of regions) {
    const line = `[${r.idx}]${r.page == null ? "" : ` p${r.page}`} ${String(r.text ?? "").replace(/\s+/g, " ").trim()}`;
    if (used + line.length + 1 > AGREEMENT_REGION_BLOCK_MAX_CHARS) {
      truncated = true;
      break;
    }
    lines.push(line);
    used += line.length + 1;
    shown += 1;
  }
  const prompt = [
    "THE DOCUMENT'S TEXT REGIONS, numbered:",
    "",
    ...lines,
    "",
    truncated
      ? "(The region list was truncated for length. Answer only from the regions shown; a figure you cannot see is 'not_printed'.)"
      : "",
    "Answer the eleven questions, quote every scheduled instalment the document prints, and cite",
    "the region you read each answer from.",
  ].filter((l) => l !== "").join("\n");
  return { prompt, shown, truncated };
}

/** The vision channel's user prompt. */
export function buildAgreementVisionPrompt() {
  return [
    "Read this agreement.",
    "",
    "Answer the eleven questions and quote every scheduled instalment the document prints.",
  ].join("\n");
}

/**
 * The prompt hash: which prompt text produced a stored read. The CLASS NAME inside the digest
 * moves with the version, so a v2 read can never carry a v1 read's hash even if the wire
 * vocabulary is unchanged. The two channels MUST hash differently — clara.persist_agreement_facts
 * refuses a pair whose two channels used one prompt, because that is one reading twice.
 *
 * @param {"text"|"vision"} channel
 */
export function agreementPromptHash(channel) {
  const system = channel === "text" ? AGREEMENT_TEXT_SYSTEM_PROMPT : AGREEMENT_VISION_SYSTEM_PROMPT;
  const vocabulary = channel === "text"
    ? [...AGREEMENT_RUN_FIELDS, ...AGREEMENT_ROW_FIELDS, ...AGREEMENT_CITATION_FIELDS]
    : [...AGREEMENT_RUN_FIELDS, ...AGREEMENT_ROW_FIELDS];
  return createHash("sha256")
    .update(JSON.stringify(["agreementFacts.v1", channel, system, vocabulary]), "utf8")
    .digest("hex");
}
