/** The FOUR cells a printed repayment-schedule row prints — exactly the terms of the identity the
 *  evaluator checks (principal + interest = instalment) and exactly the three columns whose sums
 *  it cross-checks against the printed totals. */
export const AGREEMENT_ROW_FIELDS = Object.freeze([
  "contract.schedule.due_date",
  "contract.schedule.instalment",
  "contract.schedule.principal",
  "contract.schedule.interest",
]);

/** Run-level questions a text-channel citation may name. All eleven: a person checking which
 *  financier an acquisition was booked against wants the same click-through as a figure. */
export const AGREEMENT_CITATION_FIELDS = Object.freeze([...AGREEMENT_RUN_FIELDS]);

/** The same 200-character bound clara._agreement_answers_ok applies to every rendering. An asset
 *  description longer than that is a refusal to READ, never a silent truncation: the memo a person
 *  reads must be the rendering the page carries. */
export const AGREEMENT_RAW_MAX_CHARS = 200;

/** The region block sent to the text channel is bounded: a long OCR pass must not become an
 *  unbounded prompt. Regions past the bound are dropped from the BLOCK, never renumbered — the
 *  idx a citation names is the database's own numbering either way. */
export const AGREEMENT_REGION_BLOCK_MAX_CHARS = 60_000;

/** A schedule longer than this is a refusal to READ, never a silent truncation — the same bound
 *  clara._agreement_answers_ok holds at the write boundary. 2000 is far past any repayment
 *  schedule a Malaysian SME's agreement prints (a 30-year mortgage-style schedule is 360). */
export const AGREEMENT_MAX_ROWS = 2000;

// ---------------------------------------------------------------------------------------
// The wire schemas.
// ---------------------------------------------------------------------------------------

const answerShape = z.object({
  state: z.enum(["value", "not_printed"]).describe("'value' when the document PRINTS this, 'not_printed' when it does not"),
  raw: z.string().nullable().describe("the document's EXACT rendering when state='value'; null when state='not_printed'"),
});

function runAnswersShape() {
  /** @type {Record<string, z.ZodTypeAny>} */
  const shape = {};
  for (const f of AGREEMENT_RUN_FIELDS) shape[f] = answerShape;
  return shape;
}

function rowCellsShape() {
  /** @type {Record<string, z.ZodTypeAny>} */
  const shape = {};
  for (const f of AGREEMENT_ROW_FIELDS) shape[f] = answerShape;
  return shape;
}

const rowShape = z.object({
  row_no: z.number().int().describe("the instalment's own printed number, 1 for the first instalment"),
  cells: z.object(rowCellsShape()),
});

const citationShape = z.object({
  field_path: z.enum(/** @type {[string, ...string[]]} */ ([...AGREEMENT_CITATION_FIELDS])),
  region_idx: z.number().int().describe("the [n] number of the region you read this from"),
});

/** The TEXT channel's wire schema: the run answers, the quoted schedule rows, and citations. */
export const agreementTextSchema = z.object({
  answers: z.object(runAnswersShape()),
  rows: z.array(rowShape),
  citations: z.array(citationShape),
});

/** The VISION channel's wire schema: the run answers and the quoted rows. NO citations — the
 *  vision channel never sees regions and writes none. */
export const agreementVisionSchema = z.object({
  answers: z.object(runAnswersShape()),
  rows: z.array(rowShape),
});

