// @frozen
//
// Behavioral closure for statementFacts_v4's `statement_facts` WITNESS PAIR. The successor to
// statementFacts.v3.behavior.mjs, and the smallest cut this family has had: ONE fact is added to
// the text channel's result and nothing else in the lane moves.
//
// ============================== WHAT v4 CHANGES ==============================
//
// #1037 — THE TEXT READ NOW CARRIES A PER-LINE SOURCE CITATION. #990 / migration 0291 gave
// `clara.bank_statement_lines` `citation_extraction_id` / `citation_page` / `citation_region`, and
// taught `clara._persist_statement_core_v2` to bank them off reader1's own raw payload lines. No
// producer could state one: v3's `lineShape` declares five keys and `toWriterLines` rebuilds every
// line from six named keys, both frozen. So every real machine-lane line rendered the
// stated-absence sentence. v4's text channel is asked for `region_idx` per line
// (statementFacts.v4.prompts.mjs) and this file resolves that index back to the region's own
// `{page, region}` through `clara.witness_citation_regions` joined to `clara.document_regions`
// (statementFacts.v4.citations.mjs), BEFORE the writer lines leave the step.
//
// WHERE THE RESOLUTION HAPPENS, AND WHY IT IS INSIDE THE READ STEP. The region lookup is read in
// the SAME `withRuntime` window as the numbered regions the prompt is built from — before the
// paid model call, not after it — so a replayed persist never re-reads the numbering, and a
// numbering that moved between the read and the persist can never re-point a line at a different
// patch of the page. Each model call is its own memoized step (v3's §3.1 note, unchanged), so the
// citation is memoized with the read that produced it.
//
// WHAT THIS FILE DOES NOT CHANGE, AND THEREFORE RE-EXPORTS RATHER THAN COPIES (`CUT-PLAN.md`
// section 2.1). `persistStatementWitnessPair`, `classifyStatementWitnessFailure`,
// `statementPersistFailureCode` and `ownsStatementWitnessLane` are v3's, imported relatively and
// re-exported by name, so the old text is hash-locked once. The persist needs no edit at all: it
// already builds `readers.reader1.lines` from the TEXT read's own lines, which is exactly where
// 0291's splice looks, and `page`/`region` ride there as two more keys on each line object.
//
// NO NEW DOOR, NO MIGRATION, NO DEPLOY ORDER. `clara.persist_statement_facts_v2(p_task uuid,
// p_payload jsonb)` is unchanged in name and argument order; 0291 already widened what it accepts
// and already carries the column, the CHECK and the persist core's guard. The refusal mapping is
// inherited for free: a malformed per-line shape raises CLR10 `{"reason":"chain_broken"}` and a
// citation on a lane with no second reader raises CLR10 `{"reason":"internal"}` — both already
// classified by `statementPersistFailureCode` below, both already proven by #990's own cells
// 990.c and 990.d. A v4 payload therefore meets a v3-era database with no window in which it
// cannot be read, and a rollback to v3 is fail-closed for free (a v3 payload simply states no
// citation, which is the state every line is in today).
//
// WHY THE TWO READ FUNCTIONS ARE COPIED AND NOT WRAPPED. Both call
// `statementWitnessPromptHash`, which by v3's own rule (3) must name v4 — including on the vision
// channel, whose prompt text did not change — so neither can be v3's function under a new name:
// the hash is a receipt about WHICH body produced a stored read, and stamping v3's on a v4 read
// would make the two indistinguishable on `clara.llm_usage_events`. Their private support
// (the retryable set, the failure-code taxonomy, the refusal/wait constructors, the engine-stamp
// guard, the per-channel authorization, the metering wrapper and the terminal settle) is
// module-private in v3 and is carried here verbatim; read v3's header for the reasoning behind
// every one of them, none of which this version revisits.
//
// THE ENGINE SNAPSHOT IS UNCHANGED, and that is a decision, not an omission. v4 reuses v2's
// services bundle and its globalThis slot exactly as v3 does: the DB router literal that stamps
// `document_processing_tasks.engine_id` (0102) is unchanged, so a v4 task's stamp matches this
// image's snapshot the moment the registry entry deploys. The pairing between
// `STATEMENT_WITNESS_ENGINE_SNAPSHOT` and that literal is a hand-checked invariant with no
// automatic gate (registry.ts's own note); it was re-checked by hand at this cut.
//
// Do NOT edit this file or its import closure once deployed. A behavioural change — INCLUDING A
// PROMPT TWEAK — ships as statementFacts.v5 with the registry repointed.

