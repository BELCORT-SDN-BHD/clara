// WHAT CLARA DOES HERE, IN ONE SENTENCE: she reads a payroll summary twice — once through the
// text channel, once through the vision channel — reports what each page PRINTS, quotes every
// employee row the page shows, and hands both readings to a deterministic evaluator that does
// every sum. She never adds anything up. She never fills a blank with zero. A figure the page
// does not print is reported as not printed.
//
// DEPLOY ORDER IS DATABASE FIRST, RUNTIME SECOND (migration 0296's header states it and this
// file's behaviour holds the other side): the persist door validates the answer envelope, so an
