// payrollFacts_v1 stays reachable until zero non-terminal runs reference it.

import {
  claimPayrollFactsTaskStepV1,
  payrollTextReadStepV1,
  payrollVisionReadStepV1,
  persistPayrollFactsStepV1,
} from "./payrollFacts.v1.impl.js";

export async function payrollFacts_v1(
  input: { task_id: string },
): Promise<{ task_id: string; outcome: string }> {
  "use workflow";
  const taskId = input.task_id;
  const claim = await claimPayrollFactsTaskStepV1(taskId);
  if (!claim.claimed) return { task_id: taskId, outcome: claim.status };
  // SEQUENTIAL, not concurrent: the two reads are independent, but running them one after the
  // other means a text-channel refusal costs no vision call. A spend decision, never a
  // correctness one.
  const textRead = await payrollTextReadStepV1(taskId, claim.doc);
  const visionRead = await payrollVisionReadStepV1(taskId, claim.doc);
  const result = await persistPayrollFactsStepV1(taskId, textRead, visionRead);
  return { task_id: taskId, outcome: result.status };
}
