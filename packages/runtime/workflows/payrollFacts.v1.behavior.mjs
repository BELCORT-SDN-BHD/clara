// payrollFacts_v1 — THE BEHAVIOUR. #945.
//
// Everything that decides what happens lives here, so the steps in payrollFacts.v1.impl.ts stay
// thin and the decisions stay unit-testable without a workflow engine, a database or a model.
//
// THE SHAPE OF ONE RUN: claim the task, read the page through the TEXT channel (the pinned OCR
// extraction's numbered regions), read the SAME page through the VISION channel (the canonical
// bytes), then ONE atomic persist that hands both readings to clara.persist_payroll_facts. The
// two reads are SEQUENTIAL, not concurrent: they are independent, but running them one after the
// other means a text-channel refusal costs no vision call. Ordering them is a spend decision,
// never a correctness one.
//
// THE MODEL NEVER SUMS AND THIS FILE NEVER SUMS EITHER. Not one arithmetic operation on a quoted
// figure appears below. The column sums, the row identities, the printed-totals cross-check and
// the channel comparison are all clara.evaluate_payroll_run_state_v1's, inside the persist
// transaction. That is the whole reason the evaluator is a database function rather than a
// runtime one: a deterministic evaluator a person can re-run is worth more than a fast one.
//
// Do NOT edit this file or its import closure once deployed.

