/** `internal` is deliberately NOT retryable — fail closed on the unknown. */
const RETRYABLE = new Set(["engine_error", "timeout", "engine_lost", "storage_error"]);

/** The two named agreement refusal codes migration 0299's widened CHECKs admit. */
export const AGREEMENT_REFUSAL_CODES = Object.freeze(["agreement_consent_inactive", "agreement_multi_client"]);

/** A refusal: terminal by nature (consent is a decision, not a fault), so it must never be
 *  retried into a second egress attempt. */
function agreementRefusal(code, message) {
  return Object.assign(new FatalError(`agreement read refused (${code}): ${message}`), { code, agreementRefusal: true });
}

/** A WAIT: neither a vendor fault nor a fact about this document — a deploy window, a kill
 *  switch, an OCR pass that has not landed. Rethrown so the step retries. */
function agreementWait(message) {
  return Object.assign(new Error(message), { code: "internal", claraRetry: true });
}

/** A WAIT whose budget is spent: terminal, settled, and it says what it had been waiting for. */
function agreementWaitExhausted(cause, waitedSeconds) {
  return Object.assign(
    new FatalError(
      `agreement task waited ${Math.round(waitedSeconds)}s past its budget without progressing`
      + ` — last reason: ${cause instanceof Error ? cause.message : String(cause)}`,
    ),
    { code: AGREEMENT_WAIT_EXHAUSTED, agreementRefusal: true, cause },
  );
}

function agreementFailureCode(err) {
  const code = String(err?.code || "internal");
  return ["engine_error", "timeout", "engine_lost", "storage_error", "corrupt", "encrypted",
    "bad_type", "limit", "internal"].includes(code) ? code : "internal";
}

/** THE PROVENANCE STAMP MUST NAME THE MODEL THAT IS ABOUT TO BE CALLED. The router stamped this
 *  task with an engine id; if this image calls a different model, the receipt would name one the
 *  read did not come from. A mismatch WAITS (the deploy window closes when both halves agree)
 *  rather than failing the document. */
function assertEngineStamp(services, ctx, taskId) {
  const expected = services?.engineSnapshot?.engineId;
  if (!expected) {
    throw agreementWait(`agreement services carry no engine snapshot; refusing to egress without a provenance stamp to check (task ${taskId})`);
  }
  if (ctx.engineId !== expected) {
    throw agreementWait(
      `agreement task ${taskId} is stamped engine_id '${ctx.engineId}' but this image calls '${expected}'`
      + " — refusing to egress under a provenance receipt naming a model it did not call",
    );
  }
}

/** Shared per-channel preamble over an ALREADY-READ context: the stamp, the single filing client,
 *  the surface, the task's live status, and the typed consent — prepared and then CONSUMED, so
 *  the authorization is spent before the bytes leave. */
async function authorizeChannel(services, withRuntime, taskId, doc, ctx) {
  assertEngineStamp(services, ctx, taskId);
  if (ctx.clientStatus === "ambiguous") {
    throw agreementRefusal("agreement_multi_client", `document ${doc.document_id} resolves more than one active filing client`);
  }
  if (ctx.clientStatus !== "unique" || !ctx.clientId) {
    throw agreementWait(`agreement task ${taskId} resolves no active filing client`);
  }
  const surface = await withRuntime((client) => hasAgreementSurface(client));
  if (!surface) {
    throw agreementWait("the agreement egress/persist surface is absent; refusing to call the model unauthorized");
  }
  const status = await withRuntime((client) => readTaskStatus(client, taskId));
  if (status !== "running") {
    throw agreementWait(`agreement task ${taskId} is '${status ?? "gone"}', not running — refusing to dispatch`);
  }
  const prepared = await withRuntime((client) => prepareAgreementDispatch(client, {
    firmId: doc.firm_id, clientId: ctx.clientId, eventSeq: ctx.versionN, documentSha256: doc.sha256,
  }));
  const authorizationId = prepared?.authorization_id ?? null;
  if (prepared?.verdict !== "granted" || !authorizationId) {
    throw agreementRefusal("agreement_consent_inactive", "no live typed consent + activation for witness_extraction");
  }
  const consumed = await withRuntime((client) => consumeAgreementDispatch(client, {
    firmId: doc.firm_id, authorizationId, clientId: ctx.clientId, eventSeq: ctx.versionN, documentSha256: doc.sha256,
  }));
  if (consumed?.verdict !== "granted") {
    throw agreementRefusal("agreement_consent_inactive", "the dispatch authorization was not consumable at dispatch time");
  }
}

/** Wrap one channel: read the context, authorize, call, meter. */
async function withMeteredChannel(services, withRuntime, taskId, doc, channel, promptHash, run) {
  const ctx = await withRuntime((client) => readAgreementContext(client, taskId, doc));
  const startedAt = Date.now();
  try {
    await authorizeChannel(services, withRuntime, taskId, doc, ctx);
    const out = await run(ctx);
    const usage = { ...(out.usage ?? {}), duration_ms: Date.now() - startedAt };
    await recordUsage(withRuntime, { doc, taskId, channel, engineId: ctx.engineId, promptHash, usage, outcome: "success" });
    return { ...out, usage, engineId: ctx.engineId };
  } catch (err) {
    if (err?.claraRetry === true) throw err;
    const outcome = err?.agreementRefusal === true
      ? "refused"
      : (agreementFailureCode(err) === "timeout" ? "timeout" : "error");
    await recordUsage(withRuntime, {
      doc, taskId, channel, engineId: ctx.engineId, promptHash,
      usage: { duration_ms: Date.now() - startedAt }, outcome,
    });
    throw err;
  }
}

/** TERMINAL OUTCOMES SETTLE THE TASK; a WAIT settles only once its budget is spent. */
async function withTerminalSettle(services, withRuntime, taskId, run) {
  const log = services?.log ?? console.error;
  try {
    return await run();
  } catch (err) {
    const verdict = classifyAgreementFailure(err);
    if (verdict.retry) {
      let budget = { spent: false, waitedSeconds: 0 };
      try {
        budget = await withRuntime((client) => waitBudgetExhausted(client, taskId));
      } catch {
        budget = { spent: false, waitedSeconds: 0 };
      }
      if (!budget.spent) throw err;
      const exhausted = agreementWaitExhausted(err, budget.waitedSeconds);
      log(`[agreement] task ${taskId} settling '${AGREEMENT_WAIT_EXHAUSTED}': ${exhausted.message}`);
      await settleAgreementFailure(withRuntime, taskId, AGREEMENT_WAIT_EXHAUSTED, log);
      throw exhausted;
    }
    await settleAgreementFailure(withRuntime, taskId, verdict.code, log);
    throw err;
  }
}

/**
 * THE ENVELOPE THE WRITER TAKES. Pure, and exported so a cell can drive it with a model object
 * and no database at all.
 *
 * ONE SHAPE, TWO CHANNELS: `{contract: {channel, answers, rows}}`, which is exactly what
 * clara._agreement_answers_ok admits and nothing more — the validator refuses an unknown member
 * of the contract object outright, so anything this function invented would be refused at the
 * write boundary rather than silently stored.
 *
 * THE ROWS ARE CARRIED, AND UNLIKE THE PAYSLIP LANE'S THEY ARE KEPT. clara.persist_payroll_facts
 * strips its per-employee quotes because #945's brief forbids persisting an employee figure;
 * #948's brief asks for the opposite in terms — the printed repayment schedule is part of what
 * Clara reads — so the writer banks them. Either way this function does not pre-emptively drop
 * them: the evaluator cannot sum quotes it was never given.
 *
 * @param {"text"|"vision"} channel
 */
export function toWriterEnvelope(channel, object) {
  const answers = object?.answers ?? {};
  const rows = Array.isArray(object?.rows) ? object.rows.slice(0, AGREEMENT_MAX_ROWS) : [];
  return {
    contract: {
      channel,
      answers,
      rows: rows.map((r) => ({ row_no: r?.row_no, cells: r?.cells ?? {} })),
    },
  };
}

/** The writer's citation list: field_path + region_idx, the two things the door resolves a
 *  locator from. A citation naming a field the model did not answer is dropped — a pointer to a
 *  figure nobody quoted is not evidence of anything. */
export function toWriterCitations(object) {
  const answers = object?.answers ?? {};
  const seen = new Set();
  const out = [];
  for (const c of Array.isArray(object?.citations) ? object.citations : []) {
    const field = String(c?.field_path ?? "");
    if (!field || seen.has(field)) continue;
    if (answers?.[field]?.state !== "value") continue;
    if (!Number.isInteger(c?.region_idx)) continue;
    seen.add(field);
    out.push({ field_path: field, region_idx: c.region_idx });
  }
  return out;
}

/** THE TEXT CHANNEL. Reads the pinned OCR extraction and its published region numbering, sends
 *  the numbered regions, and returns the writer's `p_text` call blob plus the pair's page count. */
export async function runAgreementTextRead(services, withRuntime, taskId, doc) {
  const promptHash = agreementPromptHash("text");
  return withTerminalSettle(services, withRuntime, taskId, async () => {
    const pinned = await withRuntime((client) => readPinnedOcrExtraction(client, doc));
    if (!pinned) {
      throw agreementWait(`agreement task ${taskId} has no done OCR extraction to read`);
    }
    const regions = await withRuntime((client) => readCitationRegions(client, pinned.id));
    if (regions.length === 0) {
      throw agreementWait(`agreement task ${taskId}'s pinned OCR extraction carries no regions`);
    }
    const built = buildAgreementTextPrompt({ regions });
    const out = await withMeteredChannel(services, withRuntime, taskId, doc, "text", promptHash, async () =>
      services.callAgreementModel({
        channel: "text",
        system: AGREEMENT_TEXT_SYSTEM_PROMPT,
        prompt: built.prompt,
        schema: agreementTextSchema,
      }));
    return {
      input_pin: pinned.id,
      prompt_hash: promptHash,
      envelope: toWriterEnvelope("text", out.object),
      citations: toWriterCitations(out.object),
      usage: out.usage,
      pages_used: pinned.pageCount,
    };
  });
}

/** THE VISION CHANNEL. Reads the canonical bytes, pinned by the document's own sha256. */
export async function runAgreementVisionRead(services, withRuntime, taskId, doc) {
  const promptHash = agreementPromptHash("vision");
  return withTerminalSettle(services, withRuntime, taskId, async () => {
    if (!services.agreementMediaType || !services.agreementMediaType(doc.mime_type)) {
      throw Object.assign(
        new Error(`agreement vision channel cannot read media type '${doc.mime_type}'`),
        { code: "bad_type" },
      );
    }
    if (Number(doc.byte_size) > AGREEMENT_MAX_VISION_BYTES) {
      throw Object.assign(
        new Error(`agreement vision payload is ${doc.byte_size} bytes, over the ${AGREEMENT_MAX_VISION_BYTES} pre-egress cap`),
        { code: "limit" },
      );
    }
    const inputPin = String(doc.sha256);
    const tempPath = services.taskTempPath(taskId);
    try {
      await services.downloadCanonical(doc.storage_path, tempPath, doc.sha256);
      const out = await withMeteredChannel(services, withRuntime, taskId, doc, "vision", promptHash, async () =>
        services.callAgreementModel({
          channel: "vision",
          system: AGREEMENT_VISION_SYSTEM_PROMPT,
          prompt: buildAgreementVisionPrompt(),
          schema: agreementVisionSchema,
          file: { path: tempPath, mime: doc.mime_type },
        }));
      return {
        input_pin: inputPin,
        prompt_hash: promptHash,
        envelope: toWriterEnvelope("vision", out.object),
        usage: out.usage,
      };
    } finally {
      await services.removeTempFile(tempPath).catch(() => {});
    }
  });
}

/** THE ONE PERSIST. Both readings go in together; the evaluator, the strip and the settle all
 *  happen inside that one transaction. */
export async function persistAgreementPair(services, withRuntime, taskId, textRead, visionRead) {
  const textCall = {
    input_pin: textRead.input_pin,
    prompt_hash: textRead.prompt_hash,
    envelope: textRead.envelope,
    citations: textRead.citations ?? [],
  };
  const visionCall = {
    input_pin: visionRead.input_pin,
    prompt_hash: visionRead.prompt_hash,
    envelope: visionRead.envelope,
  };
  const pagesUsed = Number.isInteger(textRead.pages_used) && textRead.pages_used >= 0 ? textRead.pages_used : null;
  const out = await withTerminalSettle(services, withRuntime, taskId, () => callWriter(
    withRuntime,
    "select clara.persist_agreement_facts($1,$2::jsonb,$3::jsonb,$4) as receipt",
    [taskId, JSON.stringify(textCall), JSON.stringify(visionCall), pagesUsed],
  ));
  return { taskId, status: "done", receipt: out };
}

/** Terminal-vs-retryable. */
export function classifyAgreementFailure(err) {
  if (err?.agreementRefusal === true || err instanceof FatalError) return { retry: false, code: String(err?.code ?? "internal") };
  const code = agreementFailureCode(err);
  if (err?.claraRetry === true || RETRYABLE.has(code)) return { retry: true, code };
  return { retry: false, code };
}

/** Pull the flat document metadata off a claim receipt. */
export function docFromReceipt(r) {
  if (!r || r.storage_path == null || r.sha256 == null) return null;
  return {
    document_id: String(r.document_id ?? ""),
    firm_id: String(r.firm_id ?? ""),
    lane: String(r.lane ?? ""),
    storage_path: String(r.storage_path),
    sha256: String(r.sha256),
    mime_type: String(r.mime_type ?? ""),
    byte_size: Number(r.byte_size ?? 0),
  };
}

/** Interpret a claim receipt (pure). */
export function interpretClaimReceipt(r) {
  const status = String(r?.status ?? "held_egress");
  const claimed = status === "running";
  return { claimed, status, doc: claimed ? docFromReceipt(r) : null };
}

/** A lane this workflow does not own must never be driven here. */
export function ownsAgreementLane(doc) {
  return !!doc && doc.lane === "contract_facts" && !!doc.storage_path && !!doc.sha256;
}
