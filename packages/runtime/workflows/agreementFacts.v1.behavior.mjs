// @frozen
//
// agreementFacts_v1 — THE BEHAVIOUR. #948.
//
// Everything that decides what happens lives here, so the steps in agreementFacts.v1.impl.ts stay
// thin and the decisions stay unit-testable without a workflow engine, a database or a model.
//
// THE SHAPE OF ONE RUN: claim the task, read the document through the TEXT channel (the pinned
// OCR extraction's numbered regions), read the SAME document through the VISION channel (the
// canonical bytes), then ONE atomic persist that hands both readings to
// clara.persist_agreement_facts. The
// two reads are SEQUENTIAL, not concurrent: they are independent, but running them one after the
// other means a text-channel refusal costs no vision call. Ordering them is a spend decision,
// never a correctness one.
//
// THE MODEL NEVER SUMS AND NEVER CLASSIFIES, AND THIS FILE DOES NEITHER EITHER. Not one
// arithmetic operation on a quoted figure, and not one keyword test on a quoted heading, appears
// below. The column sums, the row identities, the price identity, the schedule reconciliation,
// the CLASSIFICATION and the channel comparison are all
// clara.evaluate_agreement_contract_state_v1's, inside the persist transaction. That is the whole
// reason the evaluator is a database function rather than a runtime one: a deterministic
// evaluator a person can re-run is worth more than a fast one.
//
// Do NOT edit this file or its import closure once deployed.

