/** The ELEVEN questions about the run as a whole, in the brief's own order. */
export const PAYROLL_RUN_FIELDS = Object.freeze([
  "payroll.run.period",
  "payroll.run.gross_pay",
  "payroll.run.epf_employee",
  "payroll.run.epf_employer",
  "payroll.run.socso_employee",
  "payroll.run.socso_employer",
  "payroll.run.eis_employee",
  "payroll.run.eis_employer",
  "payroll.run.pcb",
  "payroll.run.hrdf_levy",
  "payroll.run.net_pay",
]);

/** The one non-monetary question: the month the run covers. */
export const PAYROLL_PERIOD_FIELD = "payroll.run.period";

/** The SIX cells a payslip row prints — exactly the terms of the identity the evaluator checks:
 *  gross minus employee EPF, SOCSO, EIS and PCB equals net. */
export const PAYROLL_ROW_FIELDS = Object.freeze([
  "payroll.row.gross_pay",
  "payroll.row.epf_employee",
  "payroll.row.socso_employee",
  "payroll.row.eis_employee",
  "payroll.row.pcb",
  "payroll.row.net_pay",
]);

/** Run-level questions a text-channel citation may name. The period is included: a person
 *  checking which month a run covers wants the same click-through as a figure. */
export const PAYROLL_CITATION_FIELDS = Object.freeze([...PAYROLL_RUN_FIELDS]);

/** The same 200-character bound clara._payroll_answers_ok applies to every rendering. */
export const PAYROLL_RAW_MAX_CHARS = 200;

/** The region block sent to the text channel is bounded: a long OCR pass must not become an
 *  unbounded prompt. Regions past the bound are dropped from the BLOCK, never renumbered — the
 *  idx a citation names is the database's own numbering either way. */
export const PAYROLL_REGION_BLOCK_MAX_CHARS = 60_000;

/** A run bigger than this is a refusal to READ, never a silent truncation — the same bound
 *  clara._payroll_answers_ok holds at the write boundary. */
export const PAYROLL_MAX_ROWS = 2000;

// ---------------------------------------------------------------------------------------
// The wire schemas.
// ---------------------------------------------------------------------------------------

const answerShape = z.object({
  state: z.enum(["value", "not_printed"]).describe("'value' when the document PRINTS this figure, 'not_printed' when it does not"),
  raw: z.string().nullable().describe("the document's EXACT rendering when state='value'; null when state='not_printed'"),
});

function runAnswersShape() {
  /** @type {Record<string, z.ZodTypeAny>} */
  const shape = {};
  for (const f of PAYROLL_RUN_FIELDS) shape[f] = answerShape;
  return shape;
}

function rowCellsShape() {
  /** @type {Record<string, z.ZodTypeAny>} */
  const shape = {};
  for (const f of PAYROLL_ROW_FIELDS) shape[f] = answerShape;
  return shape;
}

const rowShape = z.object({
  row_no: z.number().int().describe("the employee row's own printed position, 1 for the first row under the header"),
  cells: z.object(rowCellsShape()),
});

const citationShape = z.object({
  field_path: z.enum(/** @type {[string, ...string[]]} */ ([...PAYROLL_CITATION_FIELDS])),
  region_idx: z.number().int().describe("the [n] number of the region you read this figure from"),
});

/** The TEXT channel's wire schema: the run answers, the quoted employee rows, and citations. */
export const payrollTextSchema = z.object({
  answers: z.object(runAnswersShape()),
  rows: z.array(rowShape),
  citations: z.array(citationShape),
});

/** The VISION channel's wire schema: the run answers and the quoted rows. NO citations — the
 *  vision channel never sees regions and writes none. */
export const payrollVisionSchema = z.object({
  answers: z.object(runAnswersShape()),
  rows: z.array(rowShape),
});

