// ---------------------------------------------------------------------------------------
// The vocabulary. These names are the DATABASE's: clara._payroll_answers_ok (migration 0296)
// admits exactly these seventeen and refuses an unknown key outright, and the eleven run-level
// names map one-to-one onto codes 0150 already seeds (gross_pay→6000, epf_employee→2100,
// epf_employer→6010, socso_employee→2110, socso_employer→6020, eis_employee→2120,
// eis_employer→6030, pcb→2130, hrdf_levy→2140/6040), so #946's drafting body reads them straight.
